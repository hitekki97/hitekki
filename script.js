const deErr = {
  name: "Bitte Namen angeben.",
  company: "Bitte Firma angeben.",
  email: "Bitte gültige E-Mail angeben.",
  phone: "Bitte Telefon angeben.",
  message: "Bitte kurz beschreiben, worum es geht."
};

const original = new Map();

function nodes() {
  return document.querySelectorAll("[data-i18n]");
}

function remember() {
  nodes().forEach((el) => {
    if (!original.has(el)) original.set(el, el.textContent);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    if (!original.has(el)) original.set(el, el.getAttribute("placeholder") || "");
  });
}

function apply(lang) {
  remember();
  document.documentElement.lang = lang;
  nodes().forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = lang === "en" && en[key] ? en[key] : original.get(el);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    el.setAttribute("placeholder", lang === "en" && en[key] ? en[key] : original.get(el));
  });
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
  });
  localStorage.setItem("hitekki-lang", lang);
}

function setFaq(open) {
  document.querySelectorAll("#faq-list details").forEach((d) => {
    d.open = open;
  });
  const btn = document.querySelector("[data-faq-toggle]");
  if (!btn) return;
  const lang = localStorage.getItem("hitekki-lang") || "de";
  btn.textContent = open
    ? lang === "en" ? en["faq.close"] : "Alle schliessen"
    : lang === "en" ? en["faq.open"] : "Alle öffnen";
  btn.dataset.open = open ? "1" : "0";
}

document.querySelectorAll("[data-lang]").forEach((btn) => {
  btn.addEventListener("click", () => apply(btn.getAttribute("data-lang")));
});

const menuBtn = document.querySelector("[data-menu]");
const mobile = document.querySelector("[data-mobile]");
if (menuBtn && mobile) {
  menuBtn.addEventListener("click", () => {
    const open = mobile.classList.toggle("open");
    menuBtn.setAttribute("aria-expanded", open ? "true" : "false");
  });
  mobile.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => {
      mobile.classList.remove("open");
      menuBtn.setAttribute("aria-expanded", "false");
    });
  });
}

const faqBtn = document.querySelector("[data-faq-toggle]");
if (faqBtn) {
  faqBtn.addEventListener("click", () => setFaq(faqBtn.dataset.open !== "1"));
}

const form = document.querySelector("[data-form]");
if (form) {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const lang = localStorage.getItem("hitekki-lang") || "de";
    const data = new FormData(form);
    const values = {
      name: String(data.get("name") || "").trim(),
      company: String(data.get("company") || "").trim(),
      email: String(data.get("email") || "").trim(),
      phone: String(data.get("phone") || "").trim(),
      message: String(data.get("message") || "").trim()
    };
    const errors = {};
    if (values.name.length < 2) errors.name = lang === "en" ? en["err.name"] : deErr.name;
    if (values.company.length < 2) errors.company = lang === "en" ? en["err.company"] : deErr.company;
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(values.email)) errors.email = lang === "en" ? en["err.email"] : deErr.email;
    if (values.phone.length < 6) errors.phone = lang === "en" ? en["err.phone"] : deErr.phone;
    if (values.message.length < 10) errors.message = lang === "en" ? en["err.message"] : deErr.message;
    form.querySelectorAll("[data-err]").forEach((el) => {
      el.textContent = errors[el.getAttribute("data-err")] || "";
    });
    if (Object.keys(errors).length) return;
    const honey = String(data.get("_honey") || "").trim();
    const thanks = document.querySelector("[data-thanks]");
    if (honey) {
      form.classList.add("hide");
      if (thanks) thanks.classList.add("show");
      return;
    }
    const button = form.querySelector("button[type=submit]");
    let errorEl = form.querySelector("[data-form-error]");
    if (!errorEl) {
      errorEl = document.createElement("p");
      errorEl.className = "error";
      errorEl.setAttribute("data-form-error", "");
      button.insertAdjacentElement("afterend", errorEl);
    }
    const sendError = lang === "en"
      ? en["form.sendError"]
      : "Die Anfrage konnte nicht gesendet werden. Bitte noch einmal versuchen oder direkt an kontakt@hitekki.ch schreiben.";
    errorEl.textContent = "";
    if (button) {
      button.disabled = true;
      button.textContent = lang === "en" ? en["form.sending"] : "Wird gesendet…";
    }
    fetch("/api/anfrage", {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({
        name: values.name,
        company: values.company,
        email: values.email,
        phone: values.phone,
        message: values.message
      })
    }).then((response) => response.json().then((result) => ({ ok: response.ok, result })).catch(() => ({ ok: false, result: {} })))
      .then(({ ok, result }) => {
        if (!ok || !result.ok) throw new Error("send");
        form.classList.add("hide");
        if (thanks) thanks.classList.add("show");
      })
      .catch(() => {
        errorEl.textContent = sendError;
        if (button) {
          button.disabled = false;
          button.textContent = lang === "en" ? en["form.submit"] : "Anfrage senden";
        }
      });
  });
}

remember();
apply(localStorage.getItem("hitekki-lang") === "en" ? "en" : "de");
